"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const source = fs.readFileSync(path.join(__dirname, "../content/zotlink.js"), "utf8");
const context = { Zotero: {} };
vm.createContext(context);
vm.runInContext(source, context);
const plugin = context.Zotero.ZotLink;
assert.equal(plugin.extractArticleHistoryFromPDF, undefined);
assert.equal(plugin.registerArticleHistoryInfoRows, undefined);
const definitions = plugin.getPDFOperationPreferenceDefinitions();
assert.equal(definitions.find(row => row[1] === "bulkAlignPDFPageLabels")[2], false);
assert.equal(definitions.find(row => row[1] === "autoAlignPDFPageLabels")[2], true);
assert.ok(!definitions.some(row => /History/.test(row[1])));
const selections = [];
plugin.getBoolPref = (key, fallback) => { selections.push(key); return fallback; };
plugin.repairAllLibraryAttachmentLinksByFileID = async () => ({});
let options;
plugin.writeAllLibraryPDFDOIMetadata = async value => { options = value; return {}; };
plugin.showSoftReport = () => {};
(async () => {
    await plugin.updateAllLibraryBySelectedOptions();
    assert.ok(selections.every(key => key.startsWith("bulk")));
    assert.equal(options.writeDOIMetadata, true);
    assert.equal(options.alignPageLabels, false);
    assert.equal(options.openToFirstPage, false);
    assert.equal(options.displayTitleFileName, false);
    const pane = fs.readFileSync(path.join(__dirname, "../content/preferences.xhtml"), "utf8");
    const buttonIDs = [...pane.matchAll(/<button id="([^"]+)"/g)].map(match => match[1]);
    assert.equal(buttonIDs[0], "zotlink-import-root-pdf-library");
    assert.equal(buttonIDs[1], "zotlink-repair-all-library-links");
    const actionRow = pane.match(/<hbox[^>]*>\s*<button id="zotlink-import-root-pdf-library"[\s\S]*?<\/hbox>/)?.[0];
    assert.ok(actionRow?.includes('id="zotlink-repair-all-library-links"'), "rebuild and repair share the first row");
    assert.equal(new Set(buttonIDs).size, buttonIDs.length);
    console.log("Independent bulk defaults, history removal and button order tests passed");
})().catch(error => { console.error(error); process.exitCode = 1; });
